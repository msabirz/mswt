#!/usr/bin/env node
// Generates design/tokens.css from tokens/design-tokens.json (W3C DTCG, draft string syntax).
// Variable names follow Tailwind v4 theme namespaces so Step 3 can reuse them in `@theme`.
// Usage: node scripts/tokens-to-css.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(root, "tokens/design-tokens.json");
const OUT = join(root, "design/tokens.css");
const tokens = JSON.parse(readFileSync(SRC, "utf8"));

function lookup(path) {
  let node = tokens;
  for (const part of path.split(".")) {
    node = node?.[part];
    if (node === undefined) throw new Error(`Unresolved token alias {${path}}`);
  }
  if (!("$value" in node)) throw new Error(`Alias {${path}} points at a group, not a token`);
  return resolve(node.$value);
}

function resolve(value) {
  if (typeof value === "string") {
    const whole = value.match(/^\{([^}]+)\}$/);
    if (whole) return lookup(whole[1]);
  }
  return value;
}

function fontStack(list) {
  return list.map((f) => (/^[a-z-]+$/.test(f) ? f : `"${f}"`)).join(", ");
}

function shadow(v) {
  return `${v.offsetX} ${v.offsetY} ${v.blur} ${v.spread} ${v.color}`;
}

// Walk a group, yielding [pathSegments, token] for every leaf token.
function* leaves(node, path = []) {
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith("$") || typeof child !== "object" || child === null) continue;
    if ("$value" in child) yield [[...path, key], child];
    else yield* leaves(child, [...path, key]);
  }
}

const vars = [];
const add = (name, value, note) => vars.push({ name, value, note });

for (const [p, t] of leaves(tokens.color)) add(`--color-${p.join("-")}`, resolve(t.$value));
for (const [p, t] of leaves(tokens.semantic)) add(`--color-${p.join("-")}`, resolve(t.$value), t.$description);
for (const [p, t] of leaves(tokens.pwa)) add(`--color-pwa-${p.join("-")}`, resolve(t.$value));
for (const [p, t] of leaves(tokens.font.family)) add(`--font-${p.join("-")}`, fontStack(resolve(t.$value)));
for (const [p, t] of leaves(tokens.font.weight)) add(`--font-weight-${p.join("-")}`, resolve(t.$value));
for (const [p, t] of leaves(tokens.font.size)) add(`--text-${p.join("-")}`, resolve(t.$value));
for (const [p, t] of leaves(tokens.font["letter-spacing"])) add(`--tracking-${p.join("-")}`, resolve(t.$value));
for (const [p, t] of leaves(tokens.font["line-height"])) {
  const [script, step] = p;
  add(script === "latin" ? `--leading-${step}` : `--leading-${script}-${step}`, resolve(t.$value));
}
for (const [p, t] of leaves(tokens.space)) add(`--spacing-${p.join("-")}`, resolve(t.$value));
for (const [p, t] of leaves(tokens.radius)) add(`--radius-${p.join("-")}`, resolve(t.$value));
for (const [p, t] of leaves(tokens["border-width"])) add(`--border-width-${p.join("-")}`, resolve(t.$value));
for (const [p, t] of leaves(tokens.shadow)) add(`--shadow-${p.join("-")}`, shadow(resolve(t.$value)));
for (const [p, t] of leaves(tokens.size)) add(`--size-${p.join("-")}`, resolve(t.$value));
for (const [p, t] of leaves(tokens.breakpoint)) add(`--breakpoint-${p.join("-")}`, resolve(t.$value));
for (const [p, t] of leaves(tokens.motion.duration)) add(`--duration-${p.join("-")}`, resolve(t.$value));
for (const [p, t] of leaves(tokens.motion.easing)) add(`--ease-${p.join("-")}`, `cubic-bezier(${resolve(t.$value).join(", ")})`);

const names = new Set();
for (const v of vars) {
  if (names.has(v.name)) throw new Error(`Duplicate CSS variable ${v.name}`);
  names.add(v.name);
}

// Indic stacks: brand Latin face first (no generic family in between, or the generic would
// swallow the Indic glyphs), then the script's own families.
const sansHead = fontStack([resolve(tokens.font.family.sans.$value)[0]]);
const indicStack = (key) => `${sansHead}, ${fontStack(resolve(tokens.font.family[key].$value))}`;

const css = `/* GENERATED by scripts/tokens-to-css.mjs from tokens/design-tokens.json — do not edit by hand. */
:root {
${vars.map((v) => `  ${v.name}: ${v.value};`).join("\n")}
}

/* Script-specific type: Montserrat stays first so Latin text inside Indic pages keeps the brand face. */
:root {
  font-family: var(--font-sans);
  line-height: var(--leading-body);
}
:lang(hi), :lang(mr) {
  font-family: ${indicStack("devanagari")};
  line-height: var(--leading-indic-body);
  --leading-tight: var(--leading-indic-tight);
  --leading-snug: var(--leading-indic-snug);
  --leading-body: var(--leading-indic-body);
  --tracking-caps: 0;
}
:lang(gu) {
  font-family: ${indicStack("gujarati")};
  line-height: var(--leading-indic-body);
  --leading-tight: var(--leading-indic-tight);
  --leading-snug: var(--leading-indic-snug);
  --leading-body: var(--leading-indic-body);
  --tracking-caps: 0;
}

@media (prefers-reduced-motion: reduce) {
  *, *::before, *::after {
    animation-duration: 0.01ms !important;
    animation-iteration-count: 1 !important;
    transition-duration: 0.01ms !important;
    scroll-behavior: auto !important;
  }
}
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf8");
  if (current !== css) {
    console.error("design/tokens.css is out of date — run: node scripts/tokens-to-css.mjs");
    process.exit(1);
  }
  console.log(`tokens.css up to date (${vars.length} variables)`);
} else {
  writeFileSync(OUT, css);
  console.log(`Wrote design/tokens.css (${vars.length} variables)`);
}
